#!/usr/bin/env node
/**
 * check-arabic-typos.mjs — فاحص الأعطاب اللغوية العربية التي تمرّ من كل البوّابات.
 *
 * الاستعمال:
 *   node check-arabic-typos.mjs <مجلد>            # src/content مثلًا
 *   node check-arabic-typos.mjs <مجلد> --quiet    # بلا سياق، للروتين
 *
 * رمز الخروج 1 عند وجود مطابقة. تنبيهٌ لا حُكم: راجع كل سطر بعينك قبل التعديل،
 * فبعض الأنماط (الأسماء الأعلام، الاقتباسات) تُنتج إيجابيات صادقة المظهر كاذبة المعنى.
 *
 * ⚠️ لا تكتب أنماطًا عربية بـ\b — الحدّ في جافاسكربت معرَّف على [A-Za-z0-9_] فلا يتحقّق
 * قبل حرف عربي ولا بعده إطلاقًا، فيُخرج **صفرًا** يُقرأ طمأنينة. استعمل W() أدناه.
 */
import { readdirSync, statSync, readFileSync, existsSync } from 'node:fs';
import { join, relative, extname } from 'node:path';

const AR = 'ء-ي';
/** حدّ كلمة عربي صريح: لا حرف عربي قبل المطابقة ولا بعدها. */
const W = (body) => new RegExp(`(^|[^${AR}])(${body})([^${AR}]|$)`, 'gu');

const RULES = [
  // ١) هاء في موضع تاء التأنيث — أشيع عطب في ناتج النماذج العربية
  //    🔴 ولا تُدرِج جذرًا يصحّ أن يلحقه **هاء الغائب**: «عام + ه» و«كامل + ه» تركيبان
  //    عربيان سليمان («خلال عامه الأول» · «خسارة جزء من رأس المال أو كامله»)، وإدراجهما
  //    أخرج ٨ إيجابيات كاذبة من ٨ — أي القاعدة على هذين الجذرين **ضجيجٌ خالص**. وأسوأ:
  //    مُصلِحٌ آليٌّ طبّقها فعلًا فأفسد ٨ مواضع صحيحة في أربعة مواقع حيّة (٤٪ من ٢٠٠
  //    استبدال). والمقياس الذي يفصل: هل الجذر **اسم** يُضاف إليه ضميرٌ؟ عام · كامل ·
  //    كبير · صغير · قديم · جديد · طويل · قصير · خاص · مهم — كلّها ترد مضافةً
  //    («صغيره وكبيره» · «قديمه وجديده» · «بكامله»). فحُذفت كلّها، وبقي ما لا يُضاف.
  { re: W('ثابته|واضحه|مختلفه|صحيحه|مناسبه|سهله|قويه|محدده|مباشره|بسيطه'),
    msg: 'هاء في موضع تاء التأنيث (ثابته ← ثابتة)' },

  // ٢) همزة قطع على وصل بعد حرف جرّ/عطف
  { re: W('بإتخاذ|إتخاذ|إستخدام|إستعمال|إختيار|إعتماد|إرتفاع|إنخفاض|إجتماع|إحترام|إهتمام|إنتظار|إستشارة|إستفسار|إستقرار|إنتقال'),
    msg: 'همزة قطع على همزة وصل (إتخاذ ← اتخاذ)' },

  // ٣) واو ساقطة من المهموز
  { re: W('مسؤليات|مسئوليات|مسؤلية|مسئولية|مسؤل|مسئول(?!ية)'),
    msg: 'واو ساقطة (مسؤليات ← مسؤوليات)' },

  // ٤) تضعيف حرف أو سقوطه في أوّل الكلمة — الصنف الذي شُحن فعلًا إلى موقع حيّ
  //    ⚠️ ولا تُدرِج «تهدئ»: «تُهدِّئ المظهر المحمر» صيغةٌ صحيحة من «هدّأ» — أخرجت
  //    ١٧ إيجابية كاذبة في أربعة مواقع. الخطأ هو «تهادئ» وحدها.
  //    ⚠️ ولا «لتتعامل»: «ضبط الأدوات لتتعامل مع النطاقات» لامُ تعليلٍ قبل مضارع
  //    مبنيٍّ للمخاطبة — صحيحةٌ تمامًا، وأخرجت ٧ إيجابيات كاذبة في ٦ مواقع وصفرَ صادقة.
  //    الخطأ هو التضعيف الثلاثي «للتتعامل» (لـ + للـ + تتعامل) وحده.
  { re: W('للتتعامل|للتتحدث|للتتواصل|حديد الهدف|حديد الأهداف|البريرة|المبررة غير|تهادئ'),
    msg: 'تضعيف/سقوط حرف (حديد الهدف ← تحديد الهدف · البريرة ← المبرَّرة · تهادئ ← تهدأ)' },

  // ٥) «وحرمة» في موضع «حِرمان» — قِيس في مقال حقيقي
  { re: W('وحرمة الطرف|حرمة الطرف|وحرمة الشخص'),
    msg: 'حرمة في موضع حِرمان' },

  // ٦) ياء مقصورة/ممدودة مقلوبة في نهايات شائعة
  //    ⚠️ «اللذين» و«اللذان» صحيحتان (مثنّى الموصول) — إدراجهما أخرج ١٨ إيجابية كاذبة من ١٩
  //    في موقع واحد. و«اللذي» وحدها آمنة: حدّ W() لا يطابقها داخل «اللذين» لأنّ ما بعدها حرف عربي.
  { re: W('الى|على الرغم من ان|اللذي|هاذا|هاذه|لاكن|لاكين'),
    msg: 'إملاء شائع (الى ← إلى · اللذي ← الذي)' },

  // ٧) تسرّب تفكير النموذج — أخطر صنف، ويمرّ من كل فاحص بنية.
  //    ⚠️ مُعاير: الأنماط تخاطب **المُستخدِم أو المهمّة**، لا أي فعل بصيغة المتكلّم المستقبل.
  //    أوّل صيغة كتبتها («سأقوم|سأعيد|دعني أ») أخرجت **٥٨ إيجابية كاذبة** على موقع ردود
  //    حقيقي: «دعني أكمل فكرتي» و«سأقوم بمراجعته» هي موضوع الموقع نفسه وعباراته المقترحة.
  //    و«بناءً على طلبك» عبارة عربية مشروعة (وهي نصّ رسالة إنستغرام نفسها في موقع استرجاع
  //    الحسابات) — أخرجت إيجابيتين كاذبتين، فحُذفت. أبقِ ما لا يقوله إلا نموذج يخاطب مُشغّله.
  //    ⚠️ و«سأعيد صياغة …» بلا تعريف حذفتُها: «اعترف بالخطأ وقل: عذرًا، سأعيد صياغة
  //    النقطة بوضوح أكثر» عبارةٌ **يقولها القارئ** في موقع ثقةٍ بالنفس. النموذج يقول
  //    «سأعيد الصياغة» معرَّفةً بلا مفعول. أبقِ المعرَّفة واحذف المضافة.
  { re: /(كما طُلب منّ?ي|كما طلبت? منّ?ي|إليك النسخة|النسخة (المعاد|المحسّ?نة|المنقّحة)|سأعيد (الصياغة|الكتابة)(?![ء-ي])|سأقوم بإعادة|بصفتي نموذ|كمساعد ذكاء|كنموذج لغ|أتمنى أن يكون (هذا|ذلك) مفيد|هل تريد منّ?ي أن|إذا أردت أن أ(ضيف|عيد|كتب)|فيما يلي النسخة)/gu,
    msg: '🔴 تسرّب تفكير النموذج إلى المتن' },
  //    ⚠️ الفرق الذي يجب أن يحكمه الفاحص: نائبُ **قالبٍ** لم يُملأ (عطب) مقابل فراغٍ
  //    **يملؤه القارئ** في نموذج رسالة (محتوى مشروع). `[Your Full Name]` في رسالة يرسلها
  //    القارئ لإنستغرام، و`+9639XXXXXXXX` في مثال صيغة هاتف: كلاهما مقصود — وإدراجهما
  //    أخرج ١٠ إيجابيات كاذبة من ١٤ في موقع واحد. فالقاعدة محصورة في النوائب القاطعة.
  //    وحتى المحصورة بقيت تُخطئ: «مثل: اقتراح تعاون مع [اسم الموقع]» في نموذج رسالةٍ
  //    يرسلها القارئ محتوًى مشروع. ونوائبُ القالب **يملكها `check-template-leftovers`**
  //    (يعرف `[املأ]` و`BRAND_NAME` وسياق المشروع) — وقاعدة تقسيم المسؤوليات في المهارة
  //    تمنع فاحصًا موازيًا. فأُسقطت من هنا، وبقي `{{…}}` وTODO وlorem وحدها قاطعةً.
  //    🔴 وبلا راية `i`: النائبُ يرد بحالة أحرفه القانونية وحدها. مع `i` طابقت
  //    «a standard todo list» في مقال إنجليزي، و«no placeholder content ("Lorem Ipsum")
  //    remains» — وهي **تعليمةُ تحقّقٍ تنهى عن النائب**، لا نائبًا. إيجابيتان كاذبتان
  //    من إيجابيتين. و`TODO` وَحدها بحروفٍ كبيرة لا ترد في نثرٍ إنجليزي طبيعي.
  // TransplantBridge: `define:vars={{ X }}` صيغة Astro لتمرير متغيّرات إلى سكربت، لا نائب قالب
  { re: /((?<!define:vars=)\{\{[^}\n]*\}\}|\bTODO\b|\bFIXME\b|lorem ipsum)/gu,
    msg: '🔴 نائب قالب لم يُملأ' },

  // ٨) 🗑 **قاعدتان حُذفتا بعد القياس، ولا تُعادا:**
  //    أ) «عنوان أقصر من ١٢ حرفًا — اشتباه ببتر»: العناوين العربية القصيرة مشروعة
  //       تمامًا («### الفيديو» · «### المكان» · «## التسعير»)، ولا تُحصى بقائمة
  //       استثناءات. أخرجت ٣٩ إيجابية كاذبة في موقع و١٥ في آخر، وصفرَ إيجابيةٍ صادقة.
  //    ب) «عنوان استفهامي بلا ؟»: ١٢٩ كاذبة من ٣٢٩ مقالًا — العنوان العربي يبدأ
  //       بـ«كيف/ما» بلا سؤال طبيعيًّا.
  //    ج) «ترقيم مكرّر» على `\.{4,}`: حشو خلايا الجداول بالنقاط تنسيقٌ مقصود (١٢ كاذبة).
  //    البترُ يُكشَف بالقراءة البشرية وبـ`**` غير المتوازنة، لا بطول العنوان.
  //    **والقاعدة العامة: قاعدةٌ إيجابياتها الكاذبة أكثر من الصادقة أسوأ من لا قاعدة** —
  //    لأنّها تُدرّب القارئ على تجاهل الفاحص كلّه.
  { re: /ـ{4,}|[؟!]{3,}/gu, msg: 'تطويل أو ترقيم مكرّر' },
];

// scripts: سكربتات الحزمة والأدوات ليست محتوى؛ و.mjs/.js/.html لمواقع يولّد محتواها سكربت (براءة، 23 نوفمبر 2026)
const SKIP_DIRS = new Set(['node_modules', '.git', 'dist', '.astro', 'public', 'scripts', 'out', 'docs', 'build']);

function walk(dir, out = []) {
  for (const e of readdirSync(dir)) {
    if (SKIP_DIRS.has(e)) continue;
    const p = join(dir, e);
    const st = statSync(p);
    if (st.isDirectory()) walk(p, out);
    else if (['.md', '.mdx', '.ts', '.astro', '.mjs', '.js', '.html', '.njk', '.json'].includes(extname(e))) out.push(p);
  }
  return out;
}

const root = process.argv[2];
const quiet = process.argv.includes('--quiet');
if (!root) {
  console.error('الاستعمال: node check-arabic-typos.mjs <مجلد> [--quiet]');
  process.exit(2);
}

// 🔴 مسارٌ غير موجود ≠ مجلدٌ فارغ. الأوّل سوءُ ضبطٍ يجب أن يوقف البوّابة، والثاني
// حالةٌ مشروعة (القالب نفسه بلا مقالات). ودمجُهما يُسقط بوّابة القالب على لا شيء.
if (!existsSync(root)) {
  console.error(`✗ لا وجود للمسار: ${root}`);
  process.exit(2);
}
const files = walk(root);
let hits = 0;
const byRule = new Map();

for (const f of files) {
  // 🔴 انزع البادئة (BOM): `﻿---` لا يطابق /^---$/ فلا يُدخَل في الواجهة الأمامية
  // أصلًا، فتُفحَص كتلة `keywords` كأنّها متن — عشرة مقالات في siteCX مرّت بهذا.
  const src = readFileSync(f, 'utf8').replace(/^﻿/, '');
  const lines = src.split(/\r?\n/);
  // تجاهل كتل الشيفرة: الأنماط لا تنطبق على أسماء المتغيّرات
  let inFence = false;
  // في الواجهة الأمامية: **فقط** title وdescription. ما عداها قد يحمل slugs
  // (`related`) أو عبارات بحث تُكتب **كما يبحث الناس** عمدًا (`keywords`:
  // «ترجمة الفيديو الى العربية») — والإبلاغ عنها إبلاغٌ عمّا لا يجوز تعديله.
  // وقِيس: بلا هذا الحصر يُخرج الفاحص ٤٥٣ مطابقة في المحفظة، جُلّها slugs
  // و‏روابط لا تُمَس — وفاحصٌ بهذه الضجّة يُدرَّب المستخدم على تجاهله.
  // وdescription يُفحَص: فيه وُجدت فعلًا «عبارات ثابته» في موقع حيّ.
  let fmBars = 0;
  lines.forEach((line, i0) => {
    const i = i0;
    if (/^---\s*$/.test(line) && fmBars < 2) { fmBars++; return; }
    // 🔴 ولا `h1`: القالب يكتب الـh1 **نسخةً حرفية من عبارة البحث** كما تُكتَب في
    // جوجل بلا همزاتٍ («هل يمكن الذهاب بسيارة ايجار من دبي الى ابوظبي؟») بينما
    // يحمل `title` العربية الصحيحة («من دبي إلى أبوظبي»). فهو من صنف `keywords`
    // لا من صنف المتن — وإدراجه أخرج إيجابيتين كاذبتين من إيجابيتين.
    if (fmBars === 1 && !/^\s*(title|description)\s*:/.test(line)) return;
    if (/^\s*```/.test(line)) { inFence = !inFence; return; }
    if (inFence) return;
    // واعزل ما لا يُمَس في المتن أيضًا: أهداف الروابط، وخصائص href/src،
    // والشيفرة المضمّنة، وأي رمز موصول بشرطة (slug). حرفٌ في slug يكسر رابطًا.
    const probe = line
      .replace(/\]\([^)\s]*\)/g, ' ')
      .replace(/(href|src|slug|url)\s*=\s*"[^"]*"/gi, ' ')
      .replace(/`[^`\n]*`/g, ' ')
      .replace(/[ء-ي0-9A-Za-z]+(?:-[ء-ي0-9A-Za-z]+)+/g, ' ');
    for (const { re, msg } of RULES) {
      re.lastIndex = 0;
      const m = re.exec(probe);
      if (!m) continue;
      hits++;
      byRule.set(msg, (byRule.get(msg) || 0) + 1);
      if (!quiet) {
        console.log(`${relative(process.cwd(), f)}:${i + 1}  ${msg}`);
        console.log(`    ${line.trim().slice(0, 160)}`);
      }
    }
  });
}

console.log(`\nملفّات مفحوصة: ${files.length} · مطابقات: ${hits}`);
if (files.length === 0) {
  // قاعدة حزمة علاء: لا أخضر على صفر. (نسخة القالب عند حسن كانت تمرّ هنا برمز 0.)
  console.error('✗ صفر ملفّات قابلة للفحص في هذا المسار — «لا مطابقات» هنا ليست نتيجة.');
  process.exit(1);
}
for (const [msg, n] of [...byRule].sort((a, b) => b[1] - a[1])) console.log(`  ${n}× ${msg}`);
if (hits === 0) console.log('✓ لا مطابقة — ولا يعني هذا سلامة اللغة: اقرأ أقوى ٣–٥ مقالات بعينك.');
process.exit(hits ? 1 : 0);
